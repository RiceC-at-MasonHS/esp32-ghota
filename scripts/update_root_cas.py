#!/usr/bin/env python3
"""Regenerate the root CA bundle compiled into GithubReleaseOTA.

GitHub release downloads touch two hosts:
  github.com                             -> Sectigo / USERTrust roots
  release-assets.githubusercontent.com   -> Let's Encrypt (ISRG) roots
The bundle covers those plus spares (DigiCert, newer Sectigo roots) so a
CA change at GitHub doesn't strand devices. Check the live chains with:

  openssl s_client -connect github.com:443 -showcerts </dev/null

Usage: scripts/update_root_cas.py [--certs-dir /etc/ssl/certs]
"""
import argparse
import pathlib
import subprocess

ROOTS = [
    "USERTrust_ECC_Certification_Authority",
    "USERTrust_RSA_Certification_Authority",
    "Sectigo_Public_Server_Authentication_Root_E46",
    "Sectigo_Public_Server_Authentication_Root_R46",
    "ISRG_Root_X1",
    "ISRG_Root_X2",
    "DigiCert_Global_Root_G2",
    "DigiCert_Global_Root_G3",
]

OUT = (pathlib.Path(__file__).resolve().parent.parent
       / "libraries/GithubReleaseOTA/src/GithubReleaseOTA_RootCAs.cpp")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--certs-dir", default="/etc/ssl/certs")
    args = ap.parse_args()

    parts = []
    for name in ROOTS:
        path = pathlib.Path(args.certs_dir) / f"{name}.pem"
        expiry = subprocess.run(
            ["openssl", "x509", "-in", str(path), "-noout", "-enddate"],
            check=True, capture_output=True, text=True).stdout.strip()
        pem = subprocess.run(
            ["openssl", "x509", "-in", str(path)],
            check=True, capture_output=True, text=True).stdout.strip()
        parts.append(f"// {name} ({expiry})\n\"" + "\\n\"\n\"".join(pem.splitlines()) + "\\n\"")

    OUT.write_text(
        "// Generated by scripts/update_root_cas.py — do not edit by hand.\n"
        "#include \"GithubReleaseOTA.h\"\n\n"
        "const char GHOTA_DEFAULT_ROOT_CAS[] =\n"
        + "\n".join(parts) + ";\n")
    print(f"wrote {OUT} ({len(ROOTS)} roots)")


if __name__ == "__main__":
    main()
