#!/usr/bin/env python3
"""Release helper for the clock firmware. Used by .github/workflows/release.yml
and runnable locally. Needs only Python 3, git and openssl.

  plan        decide which variants to rebuild vs carry forward
  build-info  print build_info.h for one variant/version
  sign        write a signed manifest-<variant>.txt for a built binary
  verify      check manifests (and binaries) against the keys in ota_keys.h
"""
import argparse
import base64
import hashlib
import json
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
VARIANTS_FILE = ROOT / "variants.json"
KEYS_FILE = ROOT / "ClockFirmware" / "ota_keys.h"
FORMAT = "ghota1"
TAG_RE = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")


def load_variants():
    return json.loads(VARIANTS_FILE.read_text())


def signed_message(variant, version, size, sha256):
    # Must match GithubReleaseOTA::_verifySignature().
    return f"{FORMAT}\n{variant}\n{version}\n{size}\n{sha256}\n".encode()


def bin_name(variant, version):
    return f"clock-{variant}-{version}.bin"


def parse_tag(tag):
    m = TAG_RE.match(tag)
    if not m:
        sys.exit(f"tag '{tag}' is not vMAJOR.MINOR.PATCH")
    return tuple(int(x) for x in m.groups())


# ---------------------------------------------------------------- plan

def changed_files(prev_tag, tag):
    out = subprocess.run(["git", "diff", "--name-only", f"{prev_tag}..{tag}"],
                         cwd=ROOT, check=True, capture_output=True, text=True).stdout
    return [line for line in out.splitlines() if line]


def under(path, prefixes):
    return any(path == p or path.startswith(p) for p in prefixes)


def cmd_plan(args):
    cfg = load_variants()
    version = ".".join(map(str, parse_tag(args.tag)))
    prev_assets = set(filter(None, args.prev_assets.split(",")))

    reason_all = None
    if args.rebuild_all:
        reason_all = "rebuild requested"
    elif not args.prev_tag:
        reason_all = "first release"
    elif parse_tag(args.prev_tag)[0] != parse_tag(args.tag)[0]:
        reason_all = "major version change"

    changed = [] if reason_all else changed_files(args.prev_tag, args.tag)
    build, carry = [], []
    for v in cfg["variants"]:
        others = [p for o in cfg["variants"] if o["id"] != v["id"] for p in o["paths"]]
        relevant = [f for f in changed
                    if not under(f, others) and not under(f, cfg["ignore_paths"])]
        if reason_all:
            why = reason_all
        elif f"manifest-{v['id']}.txt" not in prev_assets:
            why = f"no manifest in {args.prev_tag}"
        elif relevant:
            why = f"{len(relevant)} relevant file(s) changed, e.g. {relevant[0]}"
        else:
            why = None

        if why:
            build.append({"id": v["id"], "fqbn": v["fqbn"]})
            print(f"build {v['id']}: {why}", file=sys.stderr)
        else:
            carry.append(v["id"])
            print(f"carry {v['id']}: unchanged since {args.prev_tag}", file=sys.stderr)

    print(f"version={version}")
    print(f"build={json.dumps(build)}")
    print(f"carry={json.dumps(carry)}")


# ---------------------------------------------------------------- build-info

def cmd_build_info(args):
    cfg = load_variants()
    v = next((v for v in cfg["variants"] if v["id"] == args.variant), None)
    if not v:
        sys.exit(f"unknown variant {args.variant}")
    print("// Generated by scripts/ota_release.py build-info for a release build.")
    print("#pragma once")
    print(f'#define FW_VERSION "{args.version}"')
    print(f"#define {v['define']}")


# ---------------------------------------------------------------- sign

def cmd_sign(args):
    data = pathlib.Path(args.bin).read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    msg = signed_message(args.variant, args.version, len(data), sha)

    with tempfile.TemporaryDirectory() as tmp:
        msg_path = pathlib.Path(tmp) / "msg"
        msg_path.write_bytes(msg)
        sig = subprocess.run(
            ["openssl", "dgst", "-sha256", "-sign", args.key, str(msg_path)],
            check=True, capture_output=True).stdout

    out = pathlib.Path(args.out_dir) / f"manifest-{args.variant}.txt"
    out.write_text(
        f"format={FORMAT}\n"
        f"variant={args.variant}\n"
        f"version={args.version}\n"
        f"size={len(data)}\n"
        f"sha256={sha}\n"
        f"url={args.url}\n"
        f"sig={base64.b64encode(sig).decode()}\n")
    print(f"wrote {out}")


# ---------------------------------------------------------------- verify

def public_keys():
    text = KEYS_FILE.read_text()
    keys = re.findall(r"-----BEGIN PUBLIC KEY-----.*?-----END PUBLIC KEY-----", text, re.S)
    return [k for k in keys if "REPLACE_WITH" not in k]


def verify_sig(msg, sig, key_pem):
    with tempfile.TemporaryDirectory() as tmp:
        t = pathlib.Path(tmp)
        (t / "msg").write_bytes(msg)
        (t / "sig").write_bytes(sig)
        (t / "key.pem").write_text(key_pem + "\n")
        r = subprocess.run(["openssl", "dgst", "-sha256", "-verify", str(t / "key.pem"),
                            "-signature", str(t / "sig"), str(t / "msg")],
                           capture_output=True)
        return r.returncode == 0


def cmd_verify(args):
    keys = public_keys()
    if not keys:
        sys.exit(f"no public keys in {KEYS_FILE.relative_to(ROOT)}")

    ok = True
    for path in args.manifests:
        fields = dict(line.split("=", 1) for line in pathlib.Path(path).read_text().splitlines()
                      if "=" in line)
        msg = signed_message(fields["variant"], fields["version"], fields["size"], fields["sha256"])
        sig = base64.b64decode(fields["sig"])
        good = [i for i, k in enumerate(keys) if verify_sig(msg, sig, k)]
        status = f"signed by key {good[0]}" if good else "NOT signed by any key in ota_keys.h"

        if args.bin_dir and good:
            local = pathlib.Path(args.bin_dir) / fields["url"].rsplit("/", 1)[1]
            if local.exists():
                data = local.read_bytes()
                if len(data) != int(fields["size"]) or hashlib.sha256(data).hexdigest() != fields["sha256"]:
                    good, status = [], f"binary {local.name} does not match manifest"
                else:
                    status += ", binary matches"

        print(f"{path}: {fields['variant']} {fields['version']}: {status}")
        ok = ok and bool(good)
    sys.exit(0 if ok else 1)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("plan")
    p.add_argument("--tag", required=True)
    p.add_argument("--prev-tag", default="")
    p.add_argument("--prev-assets", default="", help="comma-separated asset names of the previous release")
    p.add_argument("--rebuild-all", action="store_true")
    p.set_defaults(func=cmd_plan)

    p = sub.add_parser("build-info")
    p.add_argument("--variant", required=True)
    p.add_argument("--version", required=True)
    p.set_defaults(func=cmd_build_info)

    p = sub.add_parser("sign")
    p.add_argument("--variant", required=True)
    p.add_argument("--version", required=True)
    p.add_argument("--bin", required=True)
    p.add_argument("--url", required=True)
    p.add_argument("--key", required=True, help="PEM private key file")
    p.add_argument("--out-dir", default=".")
    p.set_defaults(func=cmd_sign)

    p = sub.add_parser("verify")
    p.add_argument("manifests", nargs="+")
    p.add_argument("--bin-dir", help="also check binaries found here")
    p.set_defaults(func=cmd_verify)

    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
